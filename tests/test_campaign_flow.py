"""Fluxo HTTP com CSRF em SQLite e PostgreSQL opcional, sempre em dados isolados.

KNN_TEST_POSTGRES_URL habilita PostgreSQL local; cada teste cria e remove somente
um schema próprio. Nunca usa DATABASE_URL para escolher o banco de testes.
"""
import html
import os
import re
import threading
import unittest
import uuid
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from unittest.mock import patch
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

import database
from desafios import obter_desafio_por_id
from inglessecreto import create_app
from inglessecreto.services.participants import (
    gerar_token_participante, quantidade_descobertas,
)


POSTGRES_URL = os.environ.get("KNN_TEST_POSTGRES_URL", "")


class CampaignFlowMixin:
    postgres = False

    def setUp(self):
        if self.postgres:
            import psycopg2
            parts = urlsplit(POSTGRES_URL)
            if parts.hostname not in ("127.0.0.1", "localhost", "::1"):
                self.fail("Os testes PostgreSQL exigem uma instância local isolada.")
            schema_name = "knn_test_" + uuid.uuid4().hex
            admin = psycopg2.connect(POSTGRES_URL)
            admin.autocommit = True
            admin.cursor().execute(f'CREATE SCHEMA "{schema_name}"')

            def cleanup_schema():
                try:
                    admin.cursor().execute(f'DROP SCHEMA "{schema_name}" CASCADE')
                finally:
                    admin.close()

            self.addCleanup(cleanup_schema)
            query = dict(parse_qsl(parts.query))
            query["options"] = f"-csearch_path={schema_name}"
            url = urlunsplit(parts._replace(query=urlencode(query)))
            self.enterContext(patch.object(database, "DATABASE_URL", url))
        else:
            instance = Path(__file__).resolve().parents[1] / "instance"
            instance.mkdir(exist_ok=True)
            db_path = instance / f"flow-test-{uuid.uuid4().hex}.db"
            self.addCleanup(lambda: db_path.unlink(missing_ok=True))
            self.enterContext(patch.object(database, "DATABASE_URL", None))
            self.enterContext(patch.object(database, "DATABASE_PATH", str(db_path)))
        self.connection = database.get_connection()
        self.addCleanup(self.connection.close)
        schema = database.SCHEMA_SQLITE
        if self.postgres:
            schema = schema.replace(
                "INTEGER PRIMARY KEY AUTOINCREMENT",
                "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            )
        self.connection.executescript(schema)
        self.connection.commit()
        self.campaigns = {}
        for category in ("jogos", "frases"):
            self.campaigns[category] = self.insert_id(
                "INSERT INTO campanhas (codigo,nome,semana,frase,traducao,categoria,ativa) "
                "VALUES (?, ?, 1, 'Test', 'Teste', ?, 1) RETURNING id",
                (category, category, category),
            )
        self.qrs = []
        for i in range(25):
            if i % 2 == 0:
                local_id = self.insert_id(
                    "INSERT INTO locais (nome) VALUES (?) RETURNING id", (f"Local antigo {i}",),
                )
            category = "jogos" if i % 2 == 0 else "frases"
            code = f"PRINTED-{i:03}"
            qr_id = self.insert_id(
                "INSERT INTO qr_codes (codigo,campanha_id,local_id) VALUES (?, ?, ?) RETURNING id",
                (code, self.campaigns[category], local_id),
            )
            self.qrs.append({"id": qr_id, "codigo": code, "categoria": category,
                             "campanha_id": self.campaigns[category], "local_id": local_id})
        self.connection.commit()
        self.app = create_app()
        self.app.config.update(TESTING=True, WTF_CSRF_ENABLED=True)

    def insert_id(self, sql, args):
        return self.connection.execute(sql, args).fetchone()["id"]

    def scalar(self, sql, args=()):
        return self.connection.execute(sql, args).fetchone()["total"]

    def csrf(self, response):
        match = re.search(r'<meta name="csrf-token" content="([^"]+)"', response.get_data(as_text=True))
        self.assertIsNotNone(match)
        return html.unescape(match.group(1))

    def unlock(self, client, qr):
        page = client.get(f"/e/{qr['codigo']}")
        self.assertEqual(page.status_code, 200)
        self.assertNotIn("Local antigo", page.get_data(as_text=True))
        token = self.csrf(page)
        with client.session_transaction() as session:
            challenge_id = session[f"desafio_sorteado_{qr['codigo']}"]
        challenge = obter_desafio_por_id(challenge_id, qr["categoria"])
        self.assertIsNotNone(challenge)
        response = client.post(f"/e/{qr['codigo']}/responder", data={
            "csrf_token": token, "resposta": challenge["resposta_correta"],
        })
        self.assertEqual(response.status_code, 200)
        self.assertTrue(response.json["ok"])
        return token

    def register(self, client, qr, phone="(35) 98888-1111", token=None):
        token = token or self.unlock(client, qr)
        return client.post(f"/participar/{qr['codigo']}", data={
            "csrf_token": token, "nome": "Participante teste", "whatsapp": phone,
            "email": "flow@example.com", "idade": "30", "participacao_confirmada": "1",
        }, follow_redirects=True)

    def test_25_printed_codes_survive_idempotent_migration(self):
        database.init_db()
        after = self.connection.execute(
            "SELECT id,codigo,campanha_id,local_id FROM qr_codes ORDER BY id"
        ).fetchall()
        self.assertEqual(len(after), 25)
        for old, new in zip(self.qrs, after):
            self.assertEqual((old["id"], old["codigo"], old["campanha_id"]),
                             (new["id"], new["codigo"], new["campanha_id"]))
        self.assertEqual(len({q["local_id"] for q in after}), 1)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM app_migrations"), 1)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM locais WHERE ativo = 1"), 1)

    def test_full_http_journey_25_codes_then_repeat_without_extra_points(self):
        client = self.app.test_client()
        for count, qr in enumerate(self.qrs, 1):
            page = self.register(client, qr)
            self.assertEqual(page.status_code, 200)
            content = page.get_data(as_text=True)
            if count == 1:
                self.assertIn("COMBO KNN DESBLOQUEADO", content)
            elif count == 2:
                self.assertIn("AULA GRATUITA COM CERTIFICADO DESBLOQUEADA", content)
            elif count == 3:
                self.assertIn("ENGLISH PASS DESBLOQUEADO", content)
            else:
                self.assertIn("Você já desbloqueou o prêmio máximo", content)
                self.assertIn("não gera um prêmio adicional", content)
            self.assertNotIn("encontrou todos os QR Codes", content)
            self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM descobertas"), count)
            self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM premios"), int(count >= 3))
        # Outro navegador, sem cookie de reconhecimento, e telefone sem máscara.
        second = self.app.test_client()
        for qr in self.qrs:
            page = self.register(second, qr, "35988881111")
            self.assertEqual(page.status_code, 200)
            self.assertIn("Este QR Code já foi contabilizado", page.get_data(as_text=True))
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM usuarios"), 1)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM descobertas"), 25)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM premios"), 1)

    def test_guards_wrong_answer_missing_csrf_and_inactive_campaign(self):
        client = self.app.test_client()
        qr = self.qrs[1]
        token = self.csrf(client.get(f"/e/{qr['codigo']}"))
        no_csrf = client.post(f"/e/{qr['codigo']}/responder", data={"resposta": "A"})
        self.assertEqual(no_csrf.status_code, 400)
        wrong = client.post(f"/e/{qr['codigo']}/responder", data={"resposta": "INVALID", "csrf_token": token})
        self.assertFalse(wrong.json["ok"])
        locked = client.get(f"/participar/{qr['codigo']}")
        self.assertEqual(locked.status_code, 302)
        self.unlock(client, qr)
        self.connection.execute("UPDATE campanhas SET ativa = 0 WHERE id = ?", (qr["campanha_id"],))
        self.connection.commit()
        page = self.register(client, qr, token=token)
        self.assertEqual(page.status_code, 404)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM descobertas"), 0)

    def test_concurrent_http_third_qr_creates_one_discovery_and_one_prize(self):
        first = self.app.test_client()
        for qr in self.qrs[:2]:
            self.assertEqual(self.register(first, qr).status_code, 200)
        ready = []
        third = self.qrs[2]
        for _ in range(8):
            client = self.app.test_client()
            ready.append((client, self.unlock(client, third)))
        barrier = threading.Barrier(8)

        def send(item):
            client, token = item
            barrier.wait(timeout=10)
            response = self.register(client, third, "35988881111", token)
            return response.status_code, response.get_data(as_text=True)

        with ThreadPoolExecutor(max_workers=8) as pool:
            responses = list(pool.map(send, ready))
        self.assertTrue(all(status == 200 for status, _ in responses))
        self.assertEqual(sum("Esta leitura já havia sido contabilizada" in body for _, body in responses), 7)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM usuarios"), 1)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM descobertas"), 3)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM premios"), 1)

    def test_failed_registration_rolls_back_then_can_retry(self):
        client = self.app.test_client()
        token = self.unlock(client, self.qrs[0])
        with patch("inglessecreto.services.participants.registrar_consentimento", side_effect=RuntimeError("test rollback")):
            with self.assertRaisesRegex(RuntimeError, "test rollback"):
                self.register(client, self.qrs[0], token=token)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM usuarios"), 0)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM descobertas"), 0)
        self.assertEqual(self.register(client, self.qrs[0], token=token).status_code, 200)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM descobertas"), 1)

    def test_legacy_duplicate_cookie_counts_unique_qrs_and_preserves_used_prize(self):
        ids = []
        for phone in ("35988881111", "(35) 98888-1111"):
            ids.append(self.insert_id(
                "INSERT INTO usuarios (nome,whatsapp,email,idade) VALUES ('Legado', ?, 'legacy@example.com', 30) RETURNING id",
                (phone,),
            ))
        for user_id, qr in ((ids[0], self.qrs[0]), (ids[1], self.qrs[0]), (ids[1], self.qrs[1])):
            local = self.connection.execute("SELECT local_id FROM qr_codes WHERE id = ?", (qr["id"],)).fetchone()["local_id"]
            self.connection.execute(
                "INSERT INTO descobertas (usuario_id,campanha_id,local_id,qr_code_id) VALUES (?, ?, ?, ?)",
                (user_id, qr["campanha_id"], local, qr["id"]),
            )
        reward = self.connection.execute("SELECT id FROM recompensas ORDER BY id LIMIT 1").fetchone()["id"]
        self.connection.execute("INSERT INTO premios (usuario_id,recompensa_id,status) VALUES (?, ?, 'utilizado')", (ids[1], reward))
        self.connection.commit()
        self.assertEqual(quantidade_descobertas(ids[0]), 2)
        self.assertEqual(quantidade_descobertas(ids[1]), 2)
        client = self.app.test_client()
        client.set_cookie("knn_lead_token", gerar_token_participante(ids[1]))
        self.unlock(client, self.qrs[1])
        page = client.get(f"/participar/{self.qrs[1]['codigo']}")
        self.assertIn("Este QR Code já foi contabilizado", page.get_data(as_text=True))
        self.assertEqual(self.register(client, self.qrs[2]).status_code, 200)
        self.assertEqual(quantidade_descobertas(ids[0]), 3)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM premios"), 1)
        self.assertEqual(self.connection.execute("SELECT status FROM premios").fetchone()["status"], "utilizado")


class SQLiteCampaignFlowTests(CampaignFlowMixin, unittest.TestCase):
    pass


