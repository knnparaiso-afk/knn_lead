"""Fluxo HTTP com CSRF em SQLite e PostgreSQL opcional, sempre em dados isolados.

KNN_TEST_POSTGRES_URL habilita PostgreSQL local; cada teste cria e remove somente
um schema próprio. Nunca usa DATABASE_URL para escolher o banco de testes.
"""
import html
import os
import re
import threading
import unittest
import uuid
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from unittest.mock import patch
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

import database
from desafios import obter_desafio_por_id
from inglessecreto import create_app
from inglessecreto.services.participants import (
    gerar_token_participante, quantidade_descobertas,
)


POSTGRES_URL = os.environ.get("KNN_TEST_POSTGRES_URL", "")


class CampaignFlowMixin:
    postgres = False

    def setUp(self):
        if self.postgres:
            import psycopg2
            parts = urlsplit(POSTGRES_URL)
            if parts.hostname not in ("127.0.0.1", "localhost", "::1"):
                self.fail("Os testes PostgreSQL exigem uma instância local isolada.")
            schema_name = "knn_test_" + uuid.uuid4().hex
            admin = psycopg2.connect(POSTGRES_URL)
            admin.autocommit = True
            admin.cursor().execute(f'CREATE SCHEMA "{schema_name}"')

            def cleanup_schema():
                try:
                    admin.cursor().execute(f'DROP SCHEMA "{schema_name}" CASCADE')
                finally:
                    admin.close()

            self.addCleanup(cleanup_schema)
            query = dict(parse_qsl(parts.query))
            query["options"] = f"-csearch_path={schema_name}"
            url = urlunsplit(parts._replace(query=urlencode(query)))
            self.enterContext(patch.object(database, "DATABASE_URL", url))
        else:
            instance = Path(__file__).resolve().parents[1] / "instance"
            instance.mkdir(exist_ok=True)
            db_path = instance / f"flow-test-{uuid.uuid4().hex}.db"
            self.addCleanup(lambda: db_path.unlink(missing_ok=True))
            self.enterContext(patch.object(database, "DATABASE_URL", None))
            self.enterContext(patch.object(database, "DATABASE_PATH", str(db_path)))
        self.connection = database.get_connection()
        self.addCleanup(self.connection.close)
        schema = database.SCHEMA_SQLITE
        if self.postgres:
            schema = schema.replace(
                "INTEGER PRIMARY KEY AUTOINCREMENT",
                "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            )
        self.connection.executescript(schema)
        self.connection.commit()
        self.campaigns = {}
        for category in ("jogos", "frases"):
            self.campaigns[category] = self.insert_id(
                "INSERT INTO campanhas (codigo,nome,semana,frase,traducao,categoria,ativa) "
                "VALUES (?, ?, 1, 'Test', 'Teste', ?, 1) RETURNING id",
                (category, category, category),
            )
        self.qrs = []
        for i in range(25):
            if i % 2 == 0:
                local_id = self.insert_id(
                    "INSERT INTO locais (nome) VALUES (?) RETURNING id", (f"Local antigo {i}",),
                )
            category = "jogos" if i % 2 == 0 else "frases"
            code = f"PRINTED-{i:03}"
            qr_id = self.insert_id(
                "INSERT INTO qr_codes (codigo,campanha_id,local_id) VALUES (?, ?, ?) RETURNING id",
                (code, self.campaigns[category], local_id),
            )
            self.qrs.append({"id": qr_id, "codigo": code, "categoria": category,
                             "campanha_id": self.campaigns[category], "local_id": local_id})
        self.connection.commit()
        self.app = create_app()
        self.app.config.update(TESTING=True, WTF_CSRF_ENABLED=True)

    def insert_id(self, sql, args):
        return self.connection.execute(sql, args).fetchone()["id"]

    def scalar(self, sql, args=()):
        return self.connection.execute(sql, args).fetchone()["total"]

    def csrf(self, response):
        match = re.search(r'<meta name="csrf-token" content="([^"]+)"', response.get_data(as_text=True))
        self.assertIsNotNone(match)
        return html.unescape(match.group(1))

    def unlock(self, client, qr):
        page = client.get(f"/e/{qr['codigo']}")
        self.assertEqual(page.status_code, 200)
        self.assertNotIn("Local antigo", page.get_data(as_text=True))
        token = self.csrf(page)
        with client.session_transaction() as session:
            challenge_id = session[f"desafio_sorteado_{qr['codigo']}"]
        challenge = obter_desafio_por_id(challenge_id, qr["categoria"])
        self.assertIsNotNone(challenge)
        response = client.post(f"/e/{qr['codigo']}/responder", data={
            "csrf_token": token, "resposta": challenge["resposta_correta"],
        })
        self.assertEqual(response.status_code, 200)
        self.assertTrue(response.json["ok"])
        self.assertEqual(response.json["url"], f"/recompensa/{qr['codigo']}")
        self.assertEqual(client.get(response.json["url"]).status_code, 200)
        return token

    def register(self, client, qr, phone="(35) 98888-1111", token=None):
        token = token or self.unlock(client, qr)
        return client.post(f"/participar/{qr['codigo']}", data={
            "csrf_token": token, "nome": "Participante teste", "whatsapp": phone,
            "email": "flow@example.com", "idade": "30", "participacao_confirmada": "1",
        }, follow_redirects=True)

    def test_25_printed_codes_survive_idempotent_migration(self):
        database.init_db()
        after = self.connection.execute(
            "SELECT id,codigo,campanha_id,local_id FROM qr_codes ORDER BY id"
        ).fetchall()
        self.assertEqual(len(after), 25)
        for old, new in zip(self.qrs, after):
            self.assertEqual((old["id"], old["codigo"], old["campanha_id"]),
                             (new["id"], new["codigo"], new["campanha_id"]))
        self.assertEqual(len({q["local_id"] for q in after}), 1)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM app_migrations"), 1)
        self.assertEqual(self.scalar("SELECT COUNT(*) AS total FROM locais WHERE ativo = 1"), 1)

