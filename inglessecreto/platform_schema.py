"""Migração aditiva da plataforma. Não modifica tabelas/códigos do legado."""
import time

from database import get_connection, PostgreSQLConnection

SCHEMA = """
CREATE TABLE IF NOT EXISTS pl_campaigns (
 id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS pl_revisions (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 campaign_id INTEGER NOT NULL REFERENCES pl_campaigns(id),
 version INTEGER NOT NULL, content TEXT NOT NULL, created_at BIGINT NOT NULL,
 UNIQUE(campaign_id, version)
);
CREATE TABLE IF NOT EXISTS pl_publications (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 campaign_id INTEGER NOT NULL REFERENCES pl_campaigns(id),
 revision_id INTEGER NOT NULL REFERENCES pl_revisions(id),
 target TEXT NOT NULL CHECK(target IN ('promotion','landing','game')),
 enabled INTEGER NOT NULL DEFAULT 1,
 starts_at BIGINT NOT NULL, ends_at BIGINT, priority INTEGER NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL, actor TEXT NOT NULL,
 CHECK(ends_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS idx_pl_publication_lookup
 ON pl_publications(campaign_id, target, starts_at, id);
CREATE TABLE IF NOT EXISTS pl_sources (
 id INTEGER PRIMARY KEY AUTOINCREMENT, token TEXT NOT NULL UNIQUE,
 campaign_id INTEGER NOT NULL REFERENCES pl_campaigns(id),
 channel TEXT NOT NULL, batch TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS pl_sessions (
 id TEXT PRIMARY KEY, campaign_id INTEGER NOT NULL REFERENCES pl_campaigns(id),
 revision_id INTEGER NOT NULL REFERENCES pl_revisions(id),
 channel TEXT NOT NULL, batch TEXT NOT NULL,
 created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL,
 completed_at BIGINT, participant_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_pl_session_expiry ON pl_sessions(expires_at);
CREATE TABLE IF NOT EXISTS pl_answers (
 session_id TEXT NOT NULL REFERENCES pl_sessions(id) ON DELETE CASCADE,
 position INTEGER NOT NULL, challenge_id TEXT NOT NULL,
 answer TEXT NOT NULL, correct INTEGER NOT NULL, created_at BIGINT NOT NULL,
 PRIMARY KEY(session_id, position)
);
CREATE TABLE IF NOT EXISTS pl_benefits (
 session_id TEXT PRIMARY KEY REFERENCES pl_sessions(id) ON DELETE CASCADE,
 unlocked_at BIGINT NOT NULL, valid_until BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS pl_opportunities (
 id INTEGER PRIMARY KEY AUTOINCREMENT, reference TEXT NOT NULL UNIQUE,
 campaign_id INTEGER NOT NULL REFERENCES pl_campaigns(id),
 participant_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
 session_id TEXT NOT NULL REFERENCES pl_sessions(id),
 status TEXT NOT NULL DEFAULT 'novo', owner TEXT NOT NULL DEFAULT '',
 next_action TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL, UNIQUE(campaign_id, participant_id)
);
CREATE TABLE IF NOT EXISTS pl_appointments (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 opportunity_id INTEGER NOT NULL REFERENCES pl_opportunities(id) ON DELETE CASCADE,
 starts_at BIGINT NOT NULL, status TEXT NOT NULL DEFAULT 'agendado',
 created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS pl_commercial_history (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 opportunity_id INTEGER NOT NULL REFERENCES pl_opportunities(id) ON DELETE CASCADE,
 status TEXT NOT NULL, note TEXT NOT NULL, actor TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS pl_events (
 event_key TEXT PRIMARY KEY,
 campaign_id INTEGER NOT NULL REFERENCES pl_campaigns(id),
 revision_id INTEGER NOT NULL REFERENCES pl_revisions(id),
 session_id TEXT REFERENCES pl_sessions(id) ON DELETE SET NULL,
 event TEXT NOT NULL, day TEXT NOT NULL, channel TEXT NOT NULL,
 batch TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pl_event_retention ON pl_events(created_at);
CREATE TABLE IF NOT EXISTS pl_daily_metrics (
 day TEXT NOT NULL, campaign_id INTEGER NOT NULL, revision_id INTEGER NOT NULL,
 event TEXT NOT NULL, channel TEXT NOT NULL, batch TEXT NOT NULL,
 total INTEGER NOT NULL DEFAULT 0,
 PRIMARY KEY(day, campaign_id, revision_id, event, channel, batch)
);
"""


def init_platform():
    from .services.experience_content import initial_content
    from .services.experiences import serialize

    db = get_connection()
    try:
        if isinstance(db, PostgreSQLConnection):
            db.execute("SELECT pg_advisory_xact_lock(?)", (7193042110,))
            schema = SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                                    "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        else:
            db.execute("BEGIN IMMEDIATE")
            schema = SCHEMA
        # execute separately: sqlite executescript would commit the migration lock.
        for statement in schema.split(";"):
            if statement.strip():
                db.execute(statement)
        applied = db.execute("SELECT migration_key FROM app_migrations WHERE migration_key = ?",
                             ("campaign_platform_v1",)).fetchone()
        if not applied:
            now = int(time.time())
            campaign_id = db.execute(
                "INSERT INTO pl_campaigns (slug,name,created_at) VALUES (?,?,?) RETURNING id",
                ("black-friday", "Black Friday — Um dia em inglês", now),
            ).fetchone()["id"]
            db.execute("INSERT INTO pl_revisions (campaign_id,version,content,created_at) VALUES (?,?,?,?)",
                       (campaign_id, 1, serialize(initial_content()), now))
            # Preserve the existing landing promotion as independent editorial data.
            from .services.campaigns import filtro_campanha_vigente, parametros_vigencia
            legacy = db.execute("SELECT * FROM campanhas WHERE " + filtro_campanha_vigente() +
                                " ORDER BY id DESC LIMIT 1", parametros_vigencia()).fetchone()
            if legacy:
                content = initial_content()
                content.update(title="Inglês Secreto: Halloween Edition",
                               description="Conheça a experiência de inglês da KNN Paraisópolis.",
                               landing_title="Inglês Secreto: Halloween Edition",
                               landing_text="Descubra as experiências e oportunidades da KNN.",
                               cta="Conhecer a campanha", module="contact-only@1")
                legacy_id = db.execute(
                    "INSERT INTO pl_campaigns (slug,name,created_at) VALUES (?,?,?) RETURNING id",
                    ("halloween", "Halloween — destaque independente", now),
                ).fetchone()["id"]
                revision_id = db.execute(
                    "INSERT INTO pl_revisions (campaign_id,version,content,created_at) VALUES (?,?,?,?) RETURNING id",
                    (legacy_id, 1, serialize(content), now),
                ).fetchone()["id"]
                for target in ("promotion", "landing"):
                    db.execute(
                        "INSERT INTO pl_publications (campaign_id,revision_id,target,starts_at,created_at,actor) VALUES (?,?,?,?,?,?)",
                        (legacy_id, revision_id, target, now, now, "migration"),
                    )
            db.execute("INSERT INTO app_migrations (migration_key) VALUES (?)", ("campaign_platform_v1",))
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()
